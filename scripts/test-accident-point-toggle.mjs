import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'vite';
await build({configFile:false,logLevel:'silent',define:{'import.meta.env.BASE_URL':JSON.stringify('/')},build:{lib:{entry:resolve('src/lib/accident-points.js'),formats:['es'],fileName:()=> 'accident-points.mjs'},outDir:'.local/roads/test-accident-toggle',emptyOutDir:false,copyPublicDir:false}});
const api=await import(pathToFileURL(resolve('.local/roads/test-accident-toggle/accident-points.mjs')));
let calls=0;
globalThis.fetch=async url=>{
 calls++;assert.equal(url,'/data/roads/accidents-2024-daegu-its.json');
 if(calls===1)return new Response('',{status:503});
 return new Response(await readFile('public/data/roads/accidents-2024-daegu-its.json'));
};
await assert.rejects(()=>api.loadAccidentPoints());
const [data,again]=await Promise.all([api.loadAccidentPoints(),api.loadAccidentPoints()]);
assert.equal(data,again);assert.equal(calls,2);
assert.equal(data.features.length,5450);
assert.equal(data.features.reduce((sum,f)=>sum+f.properties.count,0),8310);
assert.equal(new Set(data.features.map(f=>f.properties.linkId)).size,5450);
assert.equal(api.pointsInBounds(data.features,data.bounds).length,5450);
assert.equal(api.pointsInBounds(data.features,[126.93,37.55,126.96,37.57]).length,0);
const daegu=api.pointsInBounds(data.features,[128.59,35.84,128.62,35.86]);
assert(daegu.length>0&&daegu.length<5450);
assert.equal(api.pointsInBounds(data.features,null).length,0);
const edge={geometry:{coordinates:[128,35]}};
assert.deepEqual(api.pointsInBounds([edge],[128,35,128,35]),[edge]);
assert.throws(()=>api.pointFeatures({identifierSystem:'level5.5',year:2024}));
assert.throws(()=>api.pointFeatures({identifierSystem:'its',year:2024,links:{x:{count:1,points:[]}},mappedAccidents:1}));
const grouped=api.pointFeatures({identifierSystem:'its',year:2024,mappedAccidents:3,links:{a:{count:2,points:[{coordinates:[128,35]},{coordinates:[130,37]}]},b:{count:1,points:[{coordinates:[129,36]}]}}});
assert.equal(grouped.features.length,2,'Different road IDs must stay separate even at identical positions');
assert.deepEqual(grouped.features[0].geometry.coordinates,[129,36]);
assert.equal(grouped.features[0].properties.count,2);
assert.equal(grouped.features[0].properties.points.length,2);
assert.equal(api.accidentCircleDiameter(1),20*2/3);
assert.equal(api.accidentCircleDiameter(4),2*api.accidentCircleDiameter(1));
assert(api.accidentCircleDiameter(9)>api.accidentCircleDiameter(4));
console.log(`PASS: 8,310 accidents merged into 5,450 road circles; independent loading, centroid, separate road IDs, count preservation, 2/3 base diameter and count scaling (${daegu.length} viewport circles)`);
