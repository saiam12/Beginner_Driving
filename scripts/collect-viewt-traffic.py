"""Collect the public View-T road table; keep resumable source pages locally."""
import argparse
import csv
import gzip
import json
import math
import time
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

SOURCE = 'https://viewt.ktdb.go.kr/cong/map/TableMove_Zeke.do'
ENDPOINT = 'https://viewt.ktdb.go.kr/cong/map/getTableInfoLink01_L01page.do'
FIELDS = {
    'lev5_5_link_id': 'LINK_ID', 'its_link_ids': 'its_link_id_row',
    'road_name': 'road_name', 'road_rank': 'road_rank', 'region': 'zone_name',
    'sido_code': 'sido_id', 'sigungu_code': 'sigungu_id', 'emd_code': 'emd_id',
    'length_km': 'k_length', 'lanes': 'lane',
    'all_weekday_aadt': 'ALL_WEEKDAYS', 'all_weekend_aadt': 'ALL_WEEKEND',
}
SIDOS = ('11', '21', '22', '23', '24', '25', '26', '29',
         '31', '32', '33', '34', '35', '36', '37', '38', '39')


def query(year, page, size, sido=None):
    # These are the parameters generated by View-T's public tablecommonfunction.js.
    data = dict(page=page, rows=size, sidx='LINK_ID', sord='asc',
                pagingnowno=1, pagetotalno=1, pageonerow=size, totalrow='',
                sortcolumn='LINK_ID', sortkind='asc',
                LinkInfoTable=f'Link_LEV5_INFO_{year}',
                ZoneCodeTable=f'ZONE_INFO_{year}', CommonCodeDetail='COMMON_CODE_DETAIL',
                NullExeptColumn='ALL_WEEKDAYS',
                TotalDataBase=f'LINK_LEV5_TRAFFICVOLUME_{year}',
                sqlRoadSelectName=','.join(f"'{rank}'" for rank in range(101, 109)),
                sqlZoneAreaColumn='sido_id' if sido else 'null',
                SqlCompareCode=sido or '0000000')
    for vehicle in ('all', 'car', 'bus', 'truck'):
        for period in ('weekdays', 'weekend'):
            for term in range(1, 5):
                data[f'{vehicle}_{period}term_{term:02}'] = '0'
    return data


def fetch(data):
    request = urllib.request.Request(ENDPOINT, urllib.parse.urlencode(data).encode(),
                                    headers={'User-Agent': 'BeginnerDriving-ViewT-collector/1.0',
                                             'Referer': SOURCE, 'Accept-Encoding': 'gzip'})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=90) as response:
                payload = response.read()
                if response.headers.get('Content-Encoding') == 'gzip':
                    payload = gzip.decompress(payload)
                result = json.loads(payload)['item']
            if not isinstance(result.get('rows'), list):
                raise ValueError('Unexpected View-T response')
            return result
        except Exception:
            if attempt == 3:
                raise
            time.sleep(2 ** (attempt + 1))


def collect(args, root, sido):
    pages = root / 'pages'
    pages.mkdir(parents=True, exist_ok=True)
    contract = {'source': SOURCE, 'endpoint': ENDPOINT, 'year': args.year,
                'pageSize': args.page_size, 'request': query(args.year, 1, args.page_size, sido)}
    contract_path = root / 'request.json'
    if contract_path.exists():
        if json.loads(contract_path.read_text('utf8')) != contract:
            raise ValueError('Resume parameters differ; use a new output directory')
    else:
        contract_path.write_text(json.dumps(contract, ensure_ascii=False, indent=2), 'utf8')
    page, expected, total = 1, None, None
    while total is None or page <= total:
        if args.max_pages is not None and page > args.max_pages:
            print(f'Checkpoint only: {page - 1}/{total} pages', flush=True)
            return
        path = pages / f'{page:05}.json.gz'
        if path.exists():
            result = json.loads(gzip.decompress(path.read_bytes()))
        else:
            result = fetch(query(args.year, page, args.page_size, sido))
            path.write_bytes(gzip.compress(json.dumps(result, ensure_ascii=False).encode(), mtime=0))
            time.sleep(0.25)
        records, count = int(result['records']), int(result['total'])
        if expected is None:
            expected, total = records, count
            if expected <= 0 or total != math.ceil(expected / args.page_size):
                raise ValueError('Unexpected paging totals')
        if records != expected or count != total or int(result['page']) != page:
            raise ValueError(f'Paging changed at page {page}; resume from a fresh snapshot')
        wanted = min(args.page_size, expected - (page - 1) * args.page_size)
        if len(result['rows']) != wanted:
            raise ValueError(f'Incomplete page {page}: {len(result["rows"])}/{wanted}')
        if page == 1 or page % 10 == 0 or page == total:
            first = result['rows'][0]
            print(f'Sido {sido}: page {page}/{total}, {expected:,} expected links; '
                  f'first={first["LINK_ID"]}, ITS={first.get("its_link_id_row")}', flush=True)
        page += 1
    seen, previous = set(), -1
    output = root / 'traffic.csv'
    with output.open('w', newline='', encoding='utf-8-sig') as stream:
        writer = csv.DictWriter(stream, fieldnames=['year', *FIELDS])
        writer.writeheader()
        for path in sorted(pages.glob('*.json.gz')):
            for row in json.loads(gzip.decompress(path.read_bytes()))['rows']:
                identifier = int(row['LINK_ID'])
                if identifier in seen or identifier <= previous:
                    raise ValueError(f'Duplicate or unsorted Level 5.5 ID: {identifier}')
                seen.add(identifier)
                previous = identifier
                writer.writerow({'year': args.year, **{name: row.get(key) for name, key in FIELDS.items()}})
    if len(seen) != expected:
        raise ValueError(f'Incomplete snapshot: {len(seen)}/{expected}')
    report = {'source': SOURCE, 'year': args.year, 'scope': f'sido {sido}, road ranks 101-108',
              'collectedAt': datetime.now(timezone.utc).isoformat(), 'complete': True,
              'records': expected, 'pages': total, 'csv': str(output)}
    (root / 'collection.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), 'utf8')
    print(json.dumps(report, ensure_ascii=False), flush=True)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--year', type=int, default=2024, choices=range(2019, 2025))
    parser.add_argument('--page-size', type=int, default=500)
    parser.add_argument('--max-pages', type=int)
    parser.add_argument('--sido', choices=SIDOS)
    parser.add_argument('--output', type=Path, default=Path('.local/viewt/2024-regional'))
    args = parser.parse_args()
    if not 1 <= args.page_size <= 1000:
        parser.error('page size must be between 1 and 1000')
    if args.sido:
        collect(args, args.output / args.sido, args.sido)
        return
    args.output.mkdir(parents=True, exist_ok=True)
    totals_path = args.output / 'nationwide-totals.json'
    if not totals_path.exists():
        totals = fetch(query(args.year, 1, 1))
        totals_path.write_text(json.dumps({'year': args.year, 'records': int(totals['records'])}), 'utf8')
    totals = json.loads(totals_path.read_text('utf8'))
    if totals['year'] != args.year:
        raise ValueError('Snapshot year differs; use a new output directory')
    reports = [collect(args, args.output / sido, sido) for sido in SIDOS]
    if any(report is None for report in reports):
        return
    rows = []
    for sido in SIDOS:
        with (args.output / sido / 'traffic.csv').open(encoding='utf-8-sig', newline='') as stream:
            rows.extend(csv.DictReader(stream))
    if len(rows) != totals['records'] or len({row['lev5_5_link_id'] for row in rows}) != len(rows):
        raise ValueError('Regional union differs from nationwide total or contains duplicate IDs')
    with (args.output / 'traffic.csv').open('w', encoding='utf-8-sig', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=['year', *FIELDS])
        writer.writeheader()
        writer.writerows(sorted(rows, key=lambda row: int(row['lev5_5_link_id'])))
    report = {'source': SOURCE, 'year': args.year, 'complete': True, 'scope': 'nationwide',
              'records': len(rows), 'regions': reports,
              'collectedAt': datetime.now(timezone.utc).isoformat()}
    (args.output / 'collection.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), 'utf8')
    print(f'COMPLETE: {len(rows):,} unique links across {len(SIDOS)} regions', flush=True)


if __name__ == '__main__':
    main()
